class BaseLLMUtils:
    def __init__(self, llm_wrapper):
        self.llm_wrapper = llm_wrapper
        self.agents = prompts

    def prepare_prompt(self, replacements, agent_name):
        agent = self.agents[agent_name]
        prompt = {'system': agent['template-system']}
        user_template = agent['template-user']

        for k, v in replacements.items():
            user_template = user_template.replace(k, v)

        prompt['user'] = user_template
        return prompt

    def get_response(self, prompt, ans_key=None):
        response = self.llm_wrapper.run(prompt)
        if ans_key:
            for line in response.split('\n'):
                if ans_key in line:
                    return line[len(ans_key):].strip()
        return response

